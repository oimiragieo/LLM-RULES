#!/usr/bin/env node
/**
 * Auto-Ignore Context Scanner
 * Generates .claudeignore entries for files exceeding the token safety threshold (80K tokens / ~320KB).
 * Usage: node auto-ignore-scanner.cjs [targetDir] [--dry-run]
 */

'use strict';

const fs = require('fs');
const path = require('path');

const CHARS_PER_TOKEN = 4;
const TOKEN_THRESHOLD = 80000;
const SIZE_THRESHOLD_BYTES = TOKEN_THRESHOLD * CHARS_PER_TOKEN; // 320,000 bytes

// Extensions to scan exclusively
const TEXT_EXTENSIONS = new Set([
  '.js',
  '.cjs',
  '.mjs',
  '.ts',
  '.mts',
  '.cts',
  '.jsx',
  '.tsx',
  '.json',
  '.yaml',
  '.yml',
  '.md',
  '.mdx',
  '.css',
  '.html',
  '.htm',
  '.py',
  '.sh',
  '.bash',
  '.txt',
  '.csv',
  '.sql',
  '.xml',
  '.log',
  '.rst',
  '.ini',
  '.toml',
  '.lock',
]);

// Directories to aggressively skip
const SKIP_DIRS = new Set([
  'node_modules',
  '.git',
  'dist',
  'build',
  '.next',
  'coverage',
  '.tmp',
  '.cache',
  'vendor',
  '__pycache__',
]);

const args = process.argv.slice(2);
const dryRun = args.includes('--dry-run');
const positionalArgs = args.filter(a => !a.startsWith('--'));
const targetDir = positionalArgs[0] ? path.resolve(positionalArgs[0]) : process.cwd();

console.log(`\n🔍 Auto-Ignore Scanner: Analyzing ${targetDir}`);
process.stderr.write(
  `   Threshold: >${TOKEN_THRESHOLD} tokens (~${(SIZE_THRESHOLD_BYTES / 1024).toFixed(0)}KB)`
);

if (!fs.existsSync(targetDir)) {
  console.error(`❌ Target directory does not exist: ${targetDir}`);
  process.exit(1);
}

const massiveFiles = [];
let totalScanned = 0;

function walk(dir, depth) {
  // Prevent runaway recursion (e.g., deep nested dependencies somehow bypassing skip lists)
  if (depth > 12) return;

  let entries;
  try {
    entries = fs.readdirSync(dir, { withFileTypes: true });
  } catch {
    return;
  }

  for (const entry of entries) {
    if (SKIP_DIRS.has(entry.name) || entry.name.startsWith('.')) {
      // Also aggressively skip hidden directories (e.g. .claude/context/, .venv)
      // except if it's the root directory itself.
      if (entry.isDirectory()) continue;
    }

    const fullPath = path.join(dir, entry.name);

    if (entry.isDirectory()) {
      walk(fullPath, depth + 1);
    } else if (entry.isFile()) {
      const ext = path.extname(entry.name).toLowerCase();

      // We only care about text-based files that would bloat context.
      // Binary files are already excluded from context natively by the LLM runner.
      if (!TEXT_EXTENSIONS.has(ext)) continue;

      totalScanned++;
      try {
        const stat = fs.statSync(fullPath);
        if (stat.size > SIZE_THRESHOLD_BYTES) {
          // Normalize to POSIX paths for .claudeignore
          const relativePath = path.relative(targetDir, fullPath).replace(/\\/g, '/');
          const tokens = Math.ceil(stat.size / CHARS_PER_TOKEN);
          massiveFiles.push({ file: relativePath, size: stat.size, tokens });
        }
      } catch {
        // Ignore stats errors
      }
    }
  }
}

walk(targetDir, 0);

console.log(`\n📊 Scanned ${totalScanned} text files.`);

if (massiveFiles.length === 0) {
  console.log(`✅ No files exceeded the ${TOKEN_THRESHOLD} token safety limit.`);
  process.exit(0);
}

// Sort largest first
massiveFiles.sort((a, b) => b.size - a.size);

console.log(`\n🚨 Found ${massiveFiles.length} massive files that will crash API contexts:`);
massiveFiles.forEach(f => {
  const sizeMb = (f.size / 1024 / 1024).toFixed(2);
  const tokenFormatted = (f.tokens / 1000).toFixed(1) + 'K';
  console.log(`   - ${f.file.padEnd(50)} [${sizeMb}MB] (~${tokenFormatted} tokens)`);
});

if (dryRun) {
  console.log('\n[Dry Run] Analysis complete. No files written.');
  process.exit(0);
}

const ignorePath = path.join(targetDir, '.claudeignore');
let existingContent = '';
let _hasExistingFile = false;

if (fs.existsSync(ignorePath)) {
  existingContent = fs.readFileSync(ignorePath, 'utf8');
  _hasExistingFile = true;
}

const IGNORE_HEADER_START = '# --- AUTO-IGNORE: MASSIVE FILES START ---';
const IGNORE_HEADER_END = '# --- AUTO-IGNORE: MASSIVE FILES END ---';

// Clean out previous block if it exists
let newContent = existingContent;
const blockRegex = new RegExp(`\\n?${IGNORE_HEADER_START}[\\s\\S]*?${IGNORE_HEADER_END}\\n?`, 'g');
newContent = newContent.replace(blockRegex, '').trim();

let appendBlock = `\n\n${IGNORE_HEADER_START}\n`;
appendBlock += `# The following files exceed ${TOKEN_THRESHOLD} tokens and will crash API limits.\n`;
appendBlock += `# Generated by auto-ignore-scanner.cjs on ${new Date().toISOString()}\n`;

massiveFiles.forEach(f => {
  // Ensure paths starting with a folder look like root-relative paths to the ignore parser
  const ignoreRule = `/${f.file}`;
  appendBlock += `${ignoreRule}\n`;
});

appendBlock += `${IGNORE_HEADER_END}\n`;

newContent += appendBlock;

fs.writeFileSync(ignorePath, newContent.trim() + '\n', 'utf8');

console.log(
  `\n💾 Successfully wrote ${massiveFiles.length} exclusion rules to ${path.relative(process.cwd(), ignorePath) || '.claudeignore'}`
);
process.exit(0);
