#!/usr/bin/env node
/**
 * Enterprise Bundle Scaffolder
 * ============================
 *
 * Generates missing enterprise bundle components for a skill.
 * Reads SKILL.md to extract name, description, tools, and best practices,
 * then generates appropriate scaffolding for each missing component.
 *
 * @module enterprise-bundle-scaffolder
 */

'use strict';

const fs = require('node:fs');
const path = require('node:path');

const {
  validateEnterpriseBundle,
  ENTERPRISE_COMPONENTS,
} = require('./enterprise-bundle-validator.cjs');

// ---------------------------------------------------------------------------
// SKILL.md Parser
// ---------------------------------------------------------------------------

/**
 * Parse frontmatter and content from a SKILL.md file.
 *
 * @param {string} content - Raw SKILL.md content
 * @returns {{ name: string, description: string, tools: string[], bestPractices: string[] }}
 */
function parseSkillMd(content) {
  const result = { name: '', description: '', tools: [], bestPractices: [] };
  if (!content || typeof content !== 'string') return result;

  const fmMatch = content.match(/^---\s*\n([\s\S]*?)\n---/);
  if (!fmMatch) return result;

  const fmBlock = fmMatch[1];

  // Extract name
  const nameMatch = fmBlock.match(/^name:\s*(.+)$/m);
  if (nameMatch) result.name = nameMatch[1].trim();

  // Extract description
  const descMatch = fmBlock.match(/^description:\s*(.+)$/m);
  if (descMatch) result.description = descMatch[1].trim();

  // Extract tools array
  const toolsMatch = fmBlock.match(/^tools:\s*\[([^\]]*)\]/m);
  if (toolsMatch) {
    result.tools = toolsMatch[1]
      .split(',')
      .map(t => t.trim())
      .filter(Boolean);
  }

  // Extract best_practices array
  const bpMatch = fmBlock.match(/^best_practices:\s*\n((?:\s+-\s+.+\n?)*)/m);
  if (bpMatch) {
    result.bestPractices = bpMatch[1]
      .split('\n')
      .map(line => line.replace(/^\s+-\s+/, '').trim())
      .filter(Boolean);
  }

  return result;
}

// ---------------------------------------------------------------------------
// Template Generators
// ---------------------------------------------------------------------------

/**
 * Generate scripts/main.cjs content.
 */
function generateMainScript(skillName, description) {
  return `#!/usr/bin/env node
'use strict';
/**
 * ${skillName} - Enterprise Skill Script
 * Auto-generated by enterprise-bundle-scaffolder
 */

const fs = require('fs');
const path = require('path');

// Parse arguments
const args = process.argv.slice(2);
const options = {};
for (let i = 0; i < args.length; i++) {
  if (args[i].startsWith('--')) {
    const key = args[i].slice(2);
    const value = args[i + 1] && !args[i + 1].startsWith('--') ? args[++i] : true;
    options[key] = value;
  }
}

if (options.help) {
  console.log(\`
${skillName} - Enterprise Skill

Usage:
  node main.cjs --check <file>    Check a file against guidelines
  node main.cjs --list            List all guidelines
  node main.cjs --help            Show this help

Description:
  ${description || 'Skill entry point for ' + skillName}
\`);
  process.exit(0);
}

if (options.list) {
  console.log('Guidelines for ${skillName}:');
  console.log('See SKILL.md for full guidelines');
  process.exit(0);
}

console.log('${skillName} skill loaded. Use with Claude for code review.');
`;
}

/**
 * Generate hooks/pre-execute.cjs content.
 */
function generatePreExecuteHook(skillName) {
  return `'use strict';
/**
 * Pre-execute hook for ${skillName}
 * Auto-generated by enterprise-bundle-scaffolder
 *
 * Validates inputs before skill execution.
 */

function preExecute(context) {
  // Validate skill invocation context
  if (!context || typeof context !== 'object') {
    return { allow: true, message: '${skillName}: no context to validate' };
  }
  return { allow: true };
}

module.exports = { preExecute };
`;
}

/**
 * Generate hooks/post-execute.cjs content.
 */
function generatePostExecuteHook(skillName) {
  return `'use strict';
/**
 * Post-execute hook for ${skillName}
 * Auto-generated by enterprise-bundle-scaffolder
 *
 * Records metrics after skill execution.
 */

function postExecute(context) {
  // Record execution metrics
  return { ok: true, skill: '${skillName}' };
}

module.exports = { postExecute };
`;
}

/**
 * Generate schemas/input.schema.json content.
 */
function generateInputSchema(skillName, description) {
  return JSON.stringify({
    $schema: 'http://json-schema.org/draft-07/schema#',
    title: skillName + 'Input',
    description: 'Input schema for ' + (description || skillName),
    type: 'object',
    additionalProperties: true,
    properties: {
      target: {
        type: 'string',
        description: 'Target file or path for the skill to operate on',
      },
      options: {
        type: 'object',
        description: 'Additional options for skill execution',
        additionalProperties: true,
      },
    },
  }, null, 2) + '\n';
}

/**
 * Generate schemas/output.schema.json content.
 */
function generateOutputSchema(skillName) {
  return JSON.stringify({
    $schema: 'http://json-schema.org/draft-07/schema#',
    title: skillName + 'Output',
    type: 'object',
    additionalProperties: true,
    properties: {
      ok: {
        type: 'boolean',
      },
      summary: {
        type: 'string',
      },
    },
  }, null, 2) + '\n';
}

/**
 * Generate rules/<skill-name>.md content.
 */
function generateRule(skillName, description, bestPractices) {
  const bpSection = bestPractices.length > 0
    ? bestPractices.map(bp => '- ' + bp).join('\n')
    : '- Follow established patterns\n- Validate inputs at boundaries';

  return `# ${skillName} Rules

## Purpose

${description || 'Rules for the ' + skillName + ' skill.'}

## Best Practices

${bpSection}

## Integration Points

See SKILL.md for complete documentation.
`;
}

/**
 * Generate commands/<skill-name>.md content.
 */
function generateCommand(skillName) {
  return `---
disable-model-invocation: true
---
Invoke the ${skillName} skill and follow it exactly as presented to you
`;
}

/**
 * Generate templates/implementation-template.md content.
 */
function generateTemplate(skillName) {
  return `# ${skillName} Implementation Template

## Goal

- Define target outcome and acceptance criteria.

## TDD

1. Red
2. Green
3. Refactor

## Verification

- lint
- format
- targeted tests
`;
}

/**
 * Generate references/research-requirements.md content.
 */
function generateReference(skillName, description) {
  const date = new Date().toISOString().slice(0, 10);
  return `# ${skillName} Research Requirements

Generated: ${date}

## Skill Description

${description || 'Research requirements for ' + skillName + '.'}

## Research Areas

- Current best practices for ${skillName}
- Industry standards and tooling
- Integration patterns

## Source References

- To be populated by skill-updater research phase
`;
}

// ---------------------------------------------------------------------------
// Component name → generator mapping
// ---------------------------------------------------------------------------

/**
 * Map component template names to their generators.
 */
function getGenerator(componentName) {
  const generators = {
    'scripts/main.cjs': (name, desc) => generateMainScript(name, desc),
    'hooks/pre-execute.cjs': (name) => generatePreExecuteHook(name),
    'hooks/post-execute.cjs': (name) => generatePostExecuteHook(name),
    'schemas/input.schema.json': (name, desc) => generateInputSchema(name, desc),
    'schemas/output.schema.json': (name) => generateOutputSchema(name),
    'templates/implementation-template.md': (name) => generateTemplate(name),
    'references/research-requirements.md': (name, desc) => generateReference(name, desc),
  };

  // For rules/<skill-name>.md and commands/<skill-name>.md, match the prefix
  if (componentName.startsWith('rules/')) return 'rule';
  if (componentName.startsWith('commands/')) return 'command';

  return generators[componentName] || null;
}

// ---------------------------------------------------------------------------
// Main Scaffolder
// ---------------------------------------------------------------------------

/**
 * Scaffold missing enterprise bundle components for a skill.
 *
 * @param {string} skillName - Skill name
 * @param {string} projectRoot - Absolute path to the project root
 * @param {Object} [options]
 * @param {boolean} [options.dryRun=false] - If true, don't write files
 * @param {string} [options.skillContent=null] - Override SKILL.md content
 * @returns {{ created: string[], skipped: string[] }}
 */
function scaffoldMissingComponents(skillName, projectRoot, options = {}) {
  const { dryRun = false, skillContent = null } = options;

  const skillDir = path.join(projectRoot, '.claude', 'skills', skillName);
  const leafName = path.basename(skillName);

  // Read SKILL.md
  let parsedSkill;
  if (skillContent) {
    parsedSkill = parseSkillMd(skillContent);
  } else {
    const skillMdPath = path.join(skillDir, 'SKILL.md');
    if (fs.existsSync(skillMdPath)) {
      parsedSkill = parseSkillMd(fs.readFileSync(skillMdPath, 'utf8'));
    } else {
      parsedSkill = { name: leafName, description: '', tools: [], bestPractices: [] };
    }
  }

  const name = parsedSkill.name || leafName;
  const desc = parsedSkill.description || '';
  const bestPractices = parsedSkill.bestPractices || [];

  // Check what's missing
  const bundle = validateEnterpriseBundle(skillName, projectRoot);

  const created = [];
  const skipped = [];

  for (const component of ENTERPRISE_COMPONENTS) {
    const resolvedName = component.name.replace('<skill-name>', leafName);

    // Check if it already exists
    if (bundle.existing.includes(resolvedName)) {
      skipped.push(resolvedName);
      continue;
    }

    // Generate content
    let content;
    if (resolvedName === 'scripts/main.cjs') {
      content = generateMainScript(name, desc);
    } else if (resolvedName === 'hooks/pre-execute.cjs') {
      content = generatePreExecuteHook(name);
    } else if (resolvedName === 'hooks/post-execute.cjs') {
      content = generatePostExecuteHook(name);
    } else if (resolvedName === 'schemas/input.schema.json') {
      content = generateInputSchema(name, desc);
    } else if (resolvedName === 'schemas/output.schema.json') {
      content = generateOutputSchema(name);
    } else if (resolvedName.startsWith('rules/')) {
      content = generateRule(name, desc, bestPractices);
    } else if (resolvedName.startsWith('commands/')) {
      content = generateCommand(name);
    } else if (resolvedName === 'templates/implementation-template.md') {
      content = generateTemplate(name);
    } else if (resolvedName === 'references/research-requirements.md') {
      content = generateReference(name, desc);
    } else {
      continue;
    }

    if (!dryRun) {
      const fullPath = path.join(skillDir, resolvedName);
      fs.mkdirSync(path.dirname(fullPath), { recursive: true });
      fs.writeFileSync(fullPath, content, 'utf8');
    }

    created.push(resolvedName);
  }

  return { created, skipped };
}

module.exports = {
  scaffoldMissingComponents,
  parseSkillMd,
};
